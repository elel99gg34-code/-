#!/usr/bin/env node
/* Builds the Windows installer.
 *
 *   node scripts/make-installer.js            # pack the app, then build the installer
 *   node scripts/make-installer.js --no-pack  # reuse an existing dist/win-unpacked
 *
 * electron-builder packages the app into dist/win-unpacked (that part works on
 * any host). The NSIS installer is then compiled here with makensis directly,
 * which keeps the whole build host-agnostic: electron-builder's own NSIS target
 * wants to execute the finished installer to produce its uninstaller, and that
 * needs a working 32-bit Windows loader on non-Windows machines. A classic
 * WriteUninstaller script does not.
 */

'use strict';

const fs = require('node:fs');
const path = require('node:path');
const { spawnSync } = require('node:child_process');

const ROOT = path.join(__dirname, '..');
const DIST = path.join(ROOT, 'dist');
const UNPACKED = path.join(DIST, 'win-unpacked');
const BUILD = path.join(ROOT, 'build');
const pkg = require(path.join(ROOT, 'package.json'));

const APP = pkg.build.productName;
const VERSION = pkg.version;
const PUBLISHER = 'RIOT MACHINE';
const REG_KEY = 'RIOT-MACHINE';
const OUTPUT = path.join(DIST, `RIOT-MACHINE-Setup-${VERSION}-x64.exe`);

/* ------------------------------------------------------------------ *
 * Tooling
 * ------------------------------------------------------------------ */
function findMakensis() {
  const cache = path.join(process.env.HOME || '/root', '.cache', 'electron-builder');
  if (fs.existsSync(cache)) {
    for (const dir of fs.readdirSync(cache)) {
      if (!dir.startsWith('nsis-3')) continue;
      const base = path.join(cache, dir);
      for (const sub of fs.readdirSync(base)) {
        const exe = path.join(base, sub, 'linux', 'makensis');
        const mac = path.join(base, sub, 'mac', 'makensis');
        if (process.platform === 'linux' && fs.existsSync(exe)) return { bin: exe, nsisDir: path.join(base, sub) };
        if (process.platform === 'darwin' && fs.existsSync(mac)) return { bin: mac, nsisDir: path.join(base, sub) };
        const win = path.join(base, sub, 'makensis.exe');
        if (process.platform === 'win32' && fs.existsSync(win)) return { bin: win, nsisDir: path.join(base, sub) };
      }
    }
  }
  const which = spawnSync('which', ['makensis'], { encoding: 'utf8' });
  if (which.status === 0) return { bin: which.stdout.trim(), nsisDir: null };
  return null;
}

function run(cmd, args, opts = {}) {
  const r = spawnSync(cmd, args, { stdio: 'inherit', cwd: ROOT, ...opts });
  if (r.status !== 0) {
    throw new Error(`${path.basename(cmd)} failed with code ${r.status}${r.error ? ': ' + r.error.message : ''}`);
  }
}

/* ------------------------------------------------------------------ *
 * The NSIS script
 * ------------------------------------------------------------------ */
function nsiScript() {
  const q = (p) => p.replace(/\\/g, '\\\\');
  return `; RIOT MACHINE — generated by scripts/make-installer.js. Do not edit by hand.

Unicode true
ManifestDPIAware true

!include "MUI2.nsh"
!include "FileFunc.nsh"
!include "LogicLib.nsh"
!include "WinVer.nsh"

!define APP_NAME     "${APP}"
!define APP_VERSION  "${VERSION}"
!define APP_EXE      "${APP}.exe"
!define PUBLISHER    "${PUBLISHER}"
!define REG_UNINST   "Software\\Microsoft\\Windows\\CurrentVersion\\Uninstall\\${REG_KEY}"
!define REG_APP      "Software\\${REG_KEY}"

Name "\${APP_NAME} \${APP_VERSION}"
OutFile "${q(OUTPUT)}"
BrandingText "\${APP_NAME} \${APP_VERSION} — 590 instruments, no samples"
InstallDir "$LOCALAPPDATA\\Programs\\\${APP_NAME}"
InstallDirRegKey HKCU "\${REG_APP}" "InstallDir"
RequestExecutionLevel user
ShowInstDetails show
ShowUnInstDetails show

SetCompressor /SOLID lzma
SetCompressorDictSize 64
SetDatablockOptimize on

VIProductVersion "\${APP_VERSION}.0"
VIAddVersionKey "ProductName"     "\${APP_NAME}"
VIAddVersionKey "FileDescription" "\${APP_NAME} installer"
VIAddVersionKey "FileVersion"     "\${APP_VERSION}"
VIAddVersionKey "ProductVersion"  "\${APP_VERSION}"
VIAddVersionKey "CompanyName"     "\${PUBLISHER}"
VIAddVersionKey "LegalCopyright"  "Copyright (c) 2026 \${PUBLISHER}"

; ---------- interface ----------
!define MUI_ABORTWARNING
!define MUI_ICON   "${q(path.join(BUILD, 'icon.ico'))}"
!define MUI_UNICON "${q(path.join(BUILD, 'icon.ico'))}"

!define MUI_WELCOMEFINISHPAGE_BITMAP "${q(path.join(BUILD, 'installer-sidebar.bmp'))}"
!define MUI_WELCOMEFINISHPAGE_BITMAP_NOSTRETCH
!define MUI_UNWELCOMEFINISHPAGE_BITMAP "${q(path.join(BUILD, 'installer-sidebar.bmp'))}"
!define MUI_UNWELCOMEFINISHPAGE_BITMAP_NOSTRETCH

!define MUI_HEADERIMAGE
!define MUI_HEADERIMAGE_RIGHT
!define MUI_HEADERIMAGE_BITMAP "${q(path.join(BUILD, 'installer-header.bmp'))}"
!define MUI_HEADERIMAGE_UNBITMAP "${q(path.join(BUILD, 'installer-header.bmp'))}"

!define MUI_WELCOMEPAGE_TITLE "\${APP_NAME}"
!define MUI_WELCOMEPAGE_TEXT "A punk electronic music studio.$\\r$\\n$\\r$\\n590 instruments, all synthesised — no sample library and no internet connection. Step sequencer, piano roll, mixer, and WAV / MP3 export.$\\r$\\n$\\r$\\nThis installs for the current user only, so it needs no administrator rights."

!define MUI_DIRECTORYPAGE_TEXT_TOP "\${APP_NAME} will be installed in the folder below. Choose another one if you prefer, then click Install."

!define MUI_FINISHPAGE_RUN "$INSTDIR\\\${APP_EXE}"
!define MUI_FINISHPAGE_RUN_TEXT "Open \${APP_NAME} now"
!define MUI_FINISHPAGE_TEXT "\${APP_NAME} is installed.$\\r$\\n$\\r$\\nYour projects are saved to:$\\r$\\n%APPDATA%\\\\\${APP_NAME}\\\\vault"

!insertmacro MUI_PAGE_WELCOME
!insertmacro MUI_PAGE_LICENSE "${q(path.join(ROOT, 'LICENSE'))}"
!insertmacro MUI_PAGE_DIRECTORY
!insertmacro MUI_PAGE_INSTFILES
!insertmacro MUI_PAGE_FINISH

!insertmacro MUI_UNPAGE_CONFIRM
!insertmacro MUI_UNPAGE_INSTFILES
!insertmacro MUI_UNPAGE_FINISH

!insertmacro MUI_LANGUAGE "English"

; ---------- install ----------
Function .onInit
  \${IfNot} \${AtLeastWin10}
    MessageBox MB_OKCANCEL|MB_ICONEXCLAMATION "\${APP_NAME} is built for Windows 10 and 11. It may not start on this version.$\\r$\\n$\\r$\\nContinue anyway?" IDOK continue
    Abort
    continue:
  \${EndIf}

  ; A previous install in the same folder is replaced in place.
  ReadRegStr $R0 HKCU "\${REG_UNINST}" "UninstallString"
  \${If} $R0 != ""
    MessageBox MB_YESNO|MB_ICONQUESTION "\${APP_NAME} is already installed.$\\r$\\n$\\r$\\nReplace it with version \${APP_VERSION}? Your saved projects are kept." IDYES +2
    Abort
  \${EndIf}
FunctionEnd

Section "\${APP_NAME}" SecMain
  SectionIn RO
  SetOutPath "$INSTDIR"

  ; Clear out a previous build's files so stale resources cannot linger.
  RMDir /r "$INSTDIR\\resources"
  RMDir /r "$INSTDIR\\locales"

  File /r "${q(UNPACKED)}\\*.*"

  CreateShortCut "$SMPROGRAMS\\\${APP_NAME}.lnk" "$INSTDIR\\\${APP_EXE}" "" "$INSTDIR\\\${APP_EXE}" 0
  CreateShortCut "$DESKTOP\\\${APP_NAME}.lnk" "$INSTDIR\\\${APP_EXE}" "" "$INSTDIR\\\${APP_EXE}" 0

  WriteRegStr HKCU "\${REG_APP}" "InstallDir" "$INSTDIR"
  WriteRegStr HKCU "\${REG_APP}" "Version" "\${APP_VERSION}"

  WriteUninstaller "$INSTDIR\\Uninstall \${APP_NAME}.exe"

  \${GetSize} "$INSTDIR" "/S=0K" $0 $1 $2
  WriteRegStr   HKCU "\${REG_UNINST}" "DisplayName"     "\${APP_NAME}"
  WriteRegStr   HKCU "\${REG_UNINST}" "DisplayVersion"  "\${APP_VERSION}"
  WriteRegStr   HKCU "\${REG_UNINST}" "DisplayIcon"     "$INSTDIR\\\${APP_EXE}"
  WriteRegStr   HKCU "\${REG_UNINST}" "Publisher"       "\${PUBLISHER}"
  WriteRegStr   HKCU "\${REG_UNINST}" "InstallLocation" "$INSTDIR"
  WriteRegStr   HKCU "\${REG_UNINST}" "UninstallString" '"$INSTDIR\\Uninstall \${APP_NAME}.exe"'
  WriteRegStr   HKCU "\${REG_UNINST}" "QuietUninstallString" '"$INSTDIR\\Uninstall \${APP_NAME}.exe" /S'
  WriteRegDWORD HKCU "\${REG_UNINST}" "EstimatedSize"   "$0"
  WriteRegDWORD HKCU "\${REG_UNINST}" "NoModify"        1
  WriteRegDWORD HKCU "\${REG_UNINST}" "NoRepair"        1
SectionEnd

; ---------- uninstall ----------
Section "Uninstall"
  Delete "$SMPROGRAMS\\\${APP_NAME}.lnk"
  Delete "$DESKTOP\\\${APP_NAME}.lnk"

  RMDir /r "$INSTDIR\\resources"
  RMDir /r "$INSTDIR\\locales"
  Delete "$INSTDIR\\*.dll"
  Delete "$INSTDIR\\*.exe"
  Delete "$INSTDIR\\*.pak"
  Delete "$INSTDIR\\*.bin"
  Delete "$INSTDIR\\*.dat"
  Delete "$INSTDIR\\*.json"
  Delete "$INSTDIR\\*.html"
  Delete "$INSTDIR\\*.txt"
  RMDir /r "$INSTDIR"

  DeleteRegKey HKCU "\${REG_UNINST}"
  DeleteRegKey HKCU "\${REG_APP}"

  ; Projects are the user's work: never remove them without asking.
  IfFileExists "$APPDATA\\\${APP_NAME}\\*.*" 0 done
    MessageBox MB_YESNO|MB_ICONQUESTION \\
      "Also delete your saved projects and renders?$\\r$\\n$\\r$\\n$APPDATA\\\\\${APP_NAME}$\\r$\\n$\\r$\\nChoose No to keep them for a future install." \\
      IDNO done
    RMDir /r "$APPDATA\\\${APP_NAME}"
  done:
SectionEnd
`;
}

/* ------------------------------------------------------------------ *
 * Main
 * ------------------------------------------------------------------ */
function main() {
  const skipPack = process.argv.includes('--no-pack');

  if (!fs.existsSync(path.join(BUILD, 'icon.ico'))) run(process.execPath, [path.join(__dirname, 'make-icons.js')]);
  if (!fs.existsSync(path.join(BUILD, 'installer-sidebar.bmp'))) run(process.execPath, [path.join(__dirname, 'make-installer-art.js')]);

  if (!skipPack || !fs.existsSync(UNPACKED)) {
    console.log('\n> packaging the app for win32 x64\n');
    const builder = path.join(ROOT, 'node_modules', '.bin', 'electron-builder');
    run(builder, ['--win', '--x64', '--dir']);
  }

  const exe = path.join(UNPACKED, `${APP}.exe`);
  if (!fs.existsSync(exe)) throw new Error(`packaged app not found at ${exe}`);

  const tool = findMakensis();
  if (!tool) {
    throw new Error(
      'makensis was not found. Run `npm run pack` once (electron-builder downloads NSIS), or install NSIS from https://nsis.sourceforge.io/'
    );
  }

  const nsi = path.join(DIST, 'riot-installer.nsi');
  fs.writeFileSync(nsi, nsiScript(), 'utf8');

  console.log(`\n> compiling the installer with ${tool.bin}\n`);
  const args = ['-V2', '-NOCD'];
  if (tool.nsisDir) args.push(`-X!AddPluginDir "${path.join(tool.nsisDir, 'Plugins', 'x86-unicode')}"`);
  args.push(nsi);

  const env = { ...process.env };
  if (tool.nsisDir) env.NSISDIR = tool.nsisDir;
  run(tool.bin, args, { env });

  const stat = fs.statSync(OUTPUT);
  console.log('\n' + '='.repeat(60));
  console.log('installer   ' + OUTPUT);
  console.log('size        ' + (stat.size / 1048576).toFixed(1) + ' MB');
  console.log('app payload ' + (dirSize(UNPACKED) / 1048576).toFixed(0) + ' MB uncompressed');
  console.log('='.repeat(60) + '\n');
}

function dirSize(dir) {
  let total = 0;
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, entry.name);
    total += entry.isDirectory() ? dirSize(p) : fs.statSync(p).size;
  }
  return total;
}

main();
